"""Single DFA description -> C++ table, switches, graph, and transition table.

Only Python's standard library is needed. Generated files are committed, so
building/using the scanner does not require Python.
"""

import argparse
import csv
import io
import json
from collections import defaultdict, deque
from pathlib import Path


KEYWORDS = {
    "if": "TOK_IF", "then": "TOK_THEN", "else": "TOK_ELSE",
    "end": "TOK_END", "while": "TOK_WHILE", "do": "TOK_DO",
    "for": "TOK_FOR", "from": "TOK_FROM", "to": "TOK_TO",
    "return": "TOK_RETURN", "case": "TOK_CASE",
}
SIGNS = {
    ":": "TOK_COLON", ":=": "TOK_ASSIGN", "=": "TOK_EQ", "!=": "TOK_NE",
    "<": "TOK_LT", "<=": "TOK_LE", ">": "TOK_GT", ">=": "TOK_GE",
    "+": "TOK_PLUS", "-": "TOK_MINUS", "*": "TOK_STAR", "/": "TOK_SLASH",
    "(": "TOK_LPAREN", ")": "TOK_RPAREN", "[": "TOK_LBRACKET",
    "]": "TOK_RBRACKET", ",": "TOK_COMMA", ";": "TOK_SEMI",
}
LETTERS = list(range(ord("A"), ord("Z") + 1)) + list(range(ord("a"), ord("z") + 1))
DIGITS = list(range(ord("0"), ord("9") + 1))
WHITESPACE = [0x20, 0x09, 0x0D, 0x0A]


def build_machine():
    names, actions, rows = [], [], []

    def state(name, action="kNoAccept"):
        index = len(names)
        names.append(name)
        actions.append(action)
        rows.append([0] * 256)
        return index

    dead = state("Q_DEAD")
    start = state("Q_START")
    ident = state("Q_IDENT", "TOK_IDENT")
    number = state("Q_NUMBER", "TOK_NUMBER")
    space = state("Q_SPACE", "kSkip")
    comment = state("Q_COMMENT", "kSkip")
    for byte in LETTERS + DIGITS:
        rows[ident][byte] = ident
    for byte in LETTERS:
        rows[start][byte] = ident
    for byte in DIGITS:
        rows[start][byte] = rows[number][byte] = number
    for byte in WHITESPACE:
        rows[start][byte] = rows[space][byte] = space
    for byte in range(256):
        if byte not in (0x0D, 0x0A):
            rows[comment][byte] = comment

    # Keyword-prefix trie, completed with transitions to the generic identifier.
    prefixes = {"": start}
    for word, token in KEYWORDS.items():
        for end in range(1, len(word) + 1):
            prefix = word[:end]
            if prefix not in prefixes:
                node = state("Q_KW_" + prefix.upper(), "TOK_IDENT")
                for byte in LETTERS + DIGITS:
                    rows[node][byte] = ident
                prefixes[prefix] = node
                rows[prefixes[prefix[:-1]]][ord(prefix[-1])] = node
        actions[prefixes[word]] = token

    # A second trie handles one/two-byte signs, including nonaccepting '!'.
    signs = {"": start}
    for spelling, token in SIGNS.items():
        for end in range(1, len(spelling) + 1):
            prefix = spelling[:end]
            if prefix not in signs:
                signs[prefix] = state("Q_SIGN_" + "_".join(f"{ord(c):02X}" for c in prefix))
                rows[signs[prefix[:-1]]][ord(prefix[-1])] = signs[prefix]
        actions[signs[spelling]] = token
    rows[signs["/"]][ord("/")] = comment

    # Exact alphabet equivalence: two bytes share a class iff ALL rows agree.
    vectors, classes, byte_class = {}, [], []
    for byte in range(256):
        vector = tuple(row[byte] for row in rows)
        if vector not in vectors:
            vectors[vector] = len(classes)
            classes.append([])
        index = vectors[vector]
        classes[index].append(byte)
        byte_class.append(index)
    transitions = [[row[group[0]] for group in classes] for row in rows]
    assert len(names) <= 256 and len(classes) <= 256
    seen, pending = {start}, deque([start])
    while pending:
        for target in transitions[pending.popleft()]:
            if target != dead and target not in seen:
                seen.add(target)
                pending.append(target)
    assert seen == set(range(1, len(names))), "unreachable state"
    assert actions[start] == "kNoAccept"
    return names, actions, transitions, classes, byte_class


def byte_ranges(values):
    runs = []
    first = last = values[0]
    for value in values[1:]:
        if value == last + 1:
            last = value
        else:
            runs.append((first, last))
            first = last = value
    runs.append((first, last))
    return ", ".join(f"0x{a:02X}" if a == b else f"0x{a:02X}-0x{b:02X}" for a, b in runs)


def generate():
    names, actions, transitions, classes, byte_class = build_machine()
    header = [
        "// Generated by generate_dfa.py. Do not edit by hand.",
        "#ifndef SNIRS_DFA_GENERATED_H", "#define SNIRS_DFA_GENERATED_H",
        '#include "scanner_table.h"', "#include <cstddef>", "#include <cstdint>",
        "namespace snirs_dfa {", "enum State : std::uint8_t {",
        *[f"    {name} = {i}," for i, name in enumerate(names)], "};",
        f"inline constexpr std::size_t kStateCount = {len(names)};",
        f"inline constexpr std::size_t kClassCount = {len(classes)};",
        "inline constexpr int kNoAccept = -1;", "inline constexpr int kSkip = -2;",
        "inline constexpr unsigned char kByteClass[256] = {",
    ]
    for i in range(0, 256, 16):
        header.append("    " + ", ".join(map(str, byte_class[i:i + 16])) + ",")
    header += ["};", "inline constexpr int kActions[kStateCount] = {"]
    header += [f"    {action}, // {name}" for name, action in zip(names, actions)]
    header += ["};", "inline constexpr State kTransitions[kStateCount][kClassCount] = {"]
    for name, row in zip(names, transitions):
        header.append("    {" + ", ".join(names[x] for x in row) + "}, // " + name)
    header += ["};", "inline constexpr State branch_delta(State state, unsigned char symbol_class) {",
               "    switch (state) {"]
    for name, row in zip(names, transitions):
        header += [f"    case {name}:", "        switch (symbol_class) {"]
        groups = defaultdict(list)
        for c, target in enumerate(row):
            if target != 0:
                groups[target].append(c)
        for target, symbols in groups.items():
            header += ["        " + " ".join(f"case {c}:" for c in symbols),
                       f"            return {names[target]};"]
        header += ["        default: return Q_DEAD;", "        }"]
    header += ["    default: return Q_DEAD;", "    }", "}", "} // namespace snirs_dfa", "#endif", ""]

    table = io.StringIO(newline="")
    writer = csv.writer(table, delimiter="\t", lineterminator="\n")
    writer.writerow(["state", "action"] + [f"C{i}" for i in range(len(classes))])
    for name, action, row in zip(names, actions, transitions):
        writer.writerow([name, action] + [names[target] for target in row])

    dot = ["// Generated by generate_dfa.py; missing edges lead to Q_DEAD.",
           "digraph Scanner {", "  rankdir=LR;", '  entry [shape=point];',
           "  entry -> Q_START;"]
    for name, action in zip(names, actions):
        if name == "Q_DEAD":
            continue
        shape = "circle" if action == "kNoAccept" else "doublecircle"
        dot.append(f"  {name} [shape={shape}, label={json.dumps(name + chr(10) + action)}];")
    for name, row in zip(names, transitions):
        groups = defaultdict(list)
        for c, target in enumerate(row):
            if target:
                groups[target].append(f"C{c}")
        for target, labels in groups.items():
            dot.append(f"  {name} -> {names[target]} [label={json.dumps(','.join(labels))}];")
    dot += ["}", ""]

    doc = [
        "# Детерминированный автомат сканера", "",
        "Сгенерировано `generate_dfa.py` из того же описания, что и оба варианта δ.", "",
        "Алфавит A = {0x00, ..., 0xFF}. Конец входа не является символом алфавита:",
        "он определяется сравнением индекса с length. Нулевой байт — обычный байт.", "",
        f"Число состояний Q: {len(names)} (все перечислены в `transitions.tsv`), включая",
        "поглощающее Q_DEAD. Начальное состояние q₀ = Q_START.",
        "F — строки с action, отличным от kNoAccept; kSkip означает пропуск.",
        "Q_START, Q_DEAD и префикс знака ! не заключительные. Все префиксы",
        "ключевых слов заключительные: неполное слово является идентификатором.", "",
        "Полная функция δ задана в `transitions.tsv`: строка — состояние,",
        "столбец Cn — класс байтов. Q_DEAD обозначает невозможность продолжения",
        "лексемы. Сканер останавливает поиск перед таким переходом и возвращается",
        "к последней заключительной позиции. Если её нет, выдаёт ошибку первого байта.", "",
        "Граф задан в `automaton.dot`. Двойной круг означает заключительное состояние.",
        "Дуги в Q_DEAD опущены; его переходы ведут в него же. Имена Cn раскрыты ниже.", "",
        "## Классы входных байтов", "",
        "Байты объединены тогда и только тогда, когда переходы из всех состояний совпадают.", "",
        "| Класс | Байты (включительные диапазоны) |", "| --- | --- |",
    ]
    doc += [f"| C{i} | {byte_ranges(group)} |" for i, group in enumerate(classes)]
    doc += [
        "", "## Пути по графу", "",
        "- `if`: Q_START → Q_KW_I → Q_KW_IF. Последняя метка TOK_IF, результат [0,2).",
        "- `if2`: тот же путь, затем Q_IDENT. Метка TOK_IDENT, результат [0,3).",
        "- `if:=15`: TOK_IF [0,2), TOK_ASSIGN [2,4), TOK_NUMBER [4,6), TOK_EOF [6,6).",
        "- `!x`: префикс ! не заключительный; на x продолжения нет. TOK_ERROR [0,1).",
        "- `/`: заключительный знак TOK_SLASH; `//` переводит в Q_COMMENT с меткой kSkip.",
        "- В Q_COMMENT все байты, кроме CR/LF, оставляют автомат в том же состоянии;",
        "  CR/LF завершают комментарий и затем распознаются как пробельный пропуск.", "",
        "Ключевые слова распознаются в самом автомате. Проверка словаря после",
        "выделения идентификатора не нужна. Переходы при продолжении буквой/цифрой",
        "обеспечивают максимальную длину; при точном совпадении метка слова имеет приоритет.", "",
        f"Таблица δ: {len(names)} × {len(classes)} однобайтовых состояний =",
        f"{len(names) * len(classes)} байт; классификация входных байтов занимает ещё 256 байт.",
        "Сканирование выполняется за O(N), память экземпляра O(1). Оба варианта используют",
        "одни классы, метки, начальное состояние и шаблон next; отличается только вычисление δ.",
        "Компилятор вправе преобразовать switch; конкретный машинный код зависит от флагов сборки.", "",
    ]
    return {"dfa_generated.h": "\n".join(header), "transitions.tsv": table.getvalue(),
            "automaton.dot": "\n".join(dot), "automaton.md": "\n".join(doc)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    stale = []
    for filename, contents in generate().items():
        path = root / filename
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != contents:
                stale.append(filename)
        else:
            path.write_text(contents, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Regenerate DFA files: " + ", ".join(stale) + "\n")
    print("DFA files are up to date." if args.check else "DFA files generated.")


if __name__ == "__main__":
    main()
